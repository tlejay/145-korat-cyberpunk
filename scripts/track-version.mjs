// Writes src/net/track-version.ts = first 32 bits of sha256(public/data/track-A.json).
// Ghosts carry it (ghost-format v2) so a ghost recorded on an older track layout is never replayed
// (fix #11). Runs before every build; tests/qa/fix.spec.ts fails if the committed value is stale.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const hash = createHash('sha256').update(readFileSync(join(root, 'public/data/track-A.json'))).digest('hex').slice(0, 8);
const out = join(root, 'src/net/track-version.ts');
const src = `// Generated by scripts/track-version.mjs — do not edit. sha256(public/data/track-A.json)[0..8].\nexport const TRACK_VERSION = 0x${hash};\n`;
let prev = '';
try { prev = readFileSync(out, 'utf8'); } catch { /* first run */ }
if (prev !== src) writeFileSync(out, src);
console.log(`track version ${hash}${prev === src ? ' (unchanged)' : ' (written)'}`);
